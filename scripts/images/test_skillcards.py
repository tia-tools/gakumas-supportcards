import json
from pathlib import Path

import pytest

from skillcards import icon_file_names, icon_stems, idol_ids, read_skill_card_data
from thumbnail import SKILLCARD_OBJECT_NAME

COMMITTED = Path(__file__).resolve().parent.parent.parent / "data" / "skillcards.generated.ts"


def card(card_id: str, upgrade: int, asset: str, per_idol: bool) -> dict:
    return {"id": card_id, "upgrade": upgrade, "art": {"asset": asset, "perIdol": per_idol}}


DATA = {
    "formatVersion": 1,
    "idols": [{"id": "hski", "name": "花海咲季"}, {"id": "ttmr", "name": "月村手毬"}],
    "cards": [
        card("p_card-01-act-1_001", 0, "img_general_skillcard_act-1_001", False),
        card("p_card-01-act-1_001", 1, "img_general_skillcard_act-1_001", False),
        card("p_card-02-act-2_009", 0, "img_general_skillcard_act-2_009", True),
        card("p_card-02-act-2_009", 1, "img_general_skillcard_act-2_009", True),
    ],
    "hifAbilities": [],
}


def module_text(data: dict) -> str:
    """The module as scripts/lib/emit.ts writes it: a header, an import with braces, then the object."""
    return (
        "// Generated by scripts/generate-cards.ts — DO NOT EDIT.\n"
        'import type { SkillCardDataFile } from "./skillcard-data-file.ts";\n\n'
        f"export const SKILL_CARD_DATA: SkillCardDataFile = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    )


def test_reads_the_object_after_the_export_not_the_import_braces():
    assert read_skill_card_data(module_text(DATA)) == DATA


def test_refuses_another_format_version():
    with pytest.raises(ValueError, match="formatVersion 1"):
        read_skill_card_data(module_text({**DATA, "formatVersion": 2}))


def test_a_per_idol_card_has_one_icon_per_playable_idol_and_levels_share_their_icons():
    assert idol_ids(DATA) == ["hski", "ttmr"]
    assert icon_stems(DATA) == ["img_general_skillcard_act-1_001", "img_general_skillcard_act-2_009-hski", "img_general_skillcard_act-2_009-ttmr"]
    assert icon_file_names(DATA) == {"img_general_skillcard_act-1_001.webp", "img_general_skillcard_act-2_009-hski.webp", "img_general_skillcard_act-2_009-ttmr.webp"}


def test_the_committed_module_reads_and_names_only_icons_the_pipeline_can_extract():
    data = read_skill_card_data(COMMITTED.read_text(encoding="utf-8"))
    per_idol = {c["art"]["asset"] for c in data["cards"] if c["art"]["perIdol"]}
    single = {c["art"]["asset"] for c in data["cards"] if not c["art"]["perIdol"]}
    stems = icon_stems(data)
    assert len(stems) == len(per_idol) * len(data["idols"]) + len(single)
    assert all(SKILLCARD_OBJECT_NAME.match(f"{stem}.unity3d") for stem in stems)
